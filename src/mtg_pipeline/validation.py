from __future__ import annotations

import re
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

from pydantic import BaseModel, Field

from mtg_pipeline.config import AppConfig
from mtg_pipeline.mana import normalize_mana_cost
from mtg_pipeline.models import SourceData
from mtg_pipeline.linked_cards import resolve_rows

VALID_RARITIES = {"common", "uncommon", "rare", "mythic", "land"}
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")
SET_ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")


class ValidationIssue(BaseModel):
    severity: str
    message: str
    row_number: int | None = None


class ValidationResult(BaseModel):
    errors: list[ValidationIssue] = Field(default_factory=list)
    warnings: list[ValidationIssue] = Field(default_factory=list)
    card_count: int = 0
    rarity_counts: dict[str, int] = Field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.errors


def validate_source(data: SourceData, config: AppConfig) -> ValidationResult:
    result = ValidationResult(card_count=len(data.card_rows))
    _validate_set_metadata(data.set_metadata, result)
    _validate_card_rows(data.card_rows, config, result)
    return result


def write_validation_report(result: ValidationResult, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"Cards: {result.card_count}",
        f"Errors: {len(result.errors)}",
        f"Warnings: {len(result.warnings)}",
        "",
        "Errors:",
    ]
    lines.extend(_format_issue(issue) for issue in result.errors)
    lines.extend(["", "Warnings:"])
    lines.extend(_format_issue(issue) for issue in result.warnings)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _validate_set_metadata(metadata: dict[str, object], result: ValidationResult) -> None:
    for field in ("set_id", "set_name", "set_code", "version"):
        if not str(metadata.get(field, "")).strip():
            result.errors.append(ValidationIssue(severity="error", message=f"Set metadata: {field} is required."))
    set_id = str(metadata.get("set_id", "")).strip()
    if set_id and not SET_ID_RE.match(set_id):
        result.errors.append(ValidationIssue(severity="error", message=f"Set metadata: set_id '{set_id}' must use lowercase letters, numbers, and hyphens, for example pokemon-mtg-set."))
    version = str(metadata.get("version", "")).strip()
    if version and not VERSION_RE.match(version):
        result.errors.append(ValidationIssue(severity="error", message=f"Set metadata: version '{version}' is not semantic versioning like 0.3.0."))


def _validate_card_rows(rows: list[dict[str, object]], config: AppConfig, result: ValidationResult) -> None:
    mapping = config.columns
    try:
        rows = resolve_rows(rows, mapping)
    except ValueError as exc:
        result.errors.append(ValidationIssue(severity="error", message=str(exc)))
        return
    result.card_count = sum(_text(row.get(mapping.record_type)) != "linked_face" for row in rows)
    required = [
        mapping.id,
        mapping.name,
        mapping.card_types,
        mapping.rarity,
        mapping.render_profile,
    ]
    if rows:
        missing = [column for column in required if column not in rows[0]]
        for column in missing:
            result.errors.append(ValidationIssue(severity="error", message=f"Cards worksheet: required column '{column}' is missing."))
        if "collector_number" in rows[0]:
            result.warnings.append(ValidationIssue(severity="warning", message="Cards worksheet: collector_number column is ignored; collector numbers are generated by the pipeline."))
        if missing:
            return

    seen_ids: set[str] = set()
    name_counter: Counter[str] = Counter()
    rarity_counter: Counter[str] = Counter()
    profiles = set(config.render_profiles.keys())
    inset_ids = {_text(row.get(mapping.link_id)) for row in rows if _text(row.get(mapping.link_type)) == "prepare"}

    for index, row in enumerate(rows, start=2):
        index = int(row.get("__row_number") or index)
        if _is_falseish(row.get(mapping.include)):
            continue
        row_id = _text(row.get(mapping.id))
        name = _text(row.get(mapping.name))
        card_types = _text(row.get(mapping.card_types))
        type_line = _derived_type_line(row, mapping)
        rarity = _text(row.get(mapping.rarity)).lower()
        artwork_url = _text(row.get(mapping.artwork_url))
        art_prompt = _text(row.get(mapping.art_prompt))
        mana_cost = _text(row.get(mapping.mana_cost))
        render_profile = _text(row.get(mapping.render_profile)) or "standard"

        for field, value in (
            (mapping.id, row_id),
            (mapping.name, name),
            (mapping.card_types, card_types),
            (mapping.rarity, rarity),
        ):
            if not value:
                result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: {field} is required."))

        if row_id and row_id in seen_ids:
            result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: id '{row_id}' is duplicated."))
        seen_ids.add(row_id)

        if rarity and rarity not in VALID_RARITIES:
            result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: rarity '{rarity}' is invalid. Expected common, uncommon, rare, mythic, or land."))
        elif rarity and _text(row.get(mapping.record_type)) != "linked_face":
            rarity_counter[rarity] += 1

        if artwork_url:
            if not _text(row.get(mapping.artist)):
                result.warnings.append(ValidationIssue(severity="warning", row_number=index, message=f"Cards row {index}: artwork_url is filled for '{name}' but artist credit is missing."))
            parsed = urlparse(artwork_url)
            if parsed.scheme and (parsed.scheme not in {"http", "https"} or not parsed.netloc):
                result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: artwork_url '{artwork_url}' must be an http/https URL."))
            elif not parsed.scheme and Path(artwork_url).is_absolute():
                result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: artwork_url local paths must be relative to the project root."))
        elif art_prompt or row_id in inset_ids:
            pass
        else:
            result.warnings.append(ValidationIssue(severity="warning", row_number=index, message=f"Cards row {index}: neither artwork_url nor art_prompt is filled for '{name}'; placeholder artwork will be used."))

        if render_profile not in profiles:
            result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: render_profile '{render_profile}' is not configured."))

        if mana_cost:
            try:
                normalize_mana_cost(mana_cost)
            except ValueError as exc:
                result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"Cards row {index}: {exc}"))

        if name:
            name_counter[name] += 1

        power = _text(row.get(mapping.power))
        toughness = _text(row.get(mapping.toughness))
        if _has_type_word(type_line, "Battle") and not _text(row.get(mapping.battle_defense)):
            result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"{row_id}: Battle requires battle_defense."))
        if _text(row.get(mapping.record_type)) == "linked_face":
            if _has_type_word(type_line, "Creature") and (not power or not toughness):
                result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"{row_id}: creature face requires power and toughness."))
            if _has_type_word(type_line, "Planeswalker") and not _text(row.get(mapping.loyalty)):
                result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"{row_id}: planeswalker face requires loyalty."))
        indicator = _text(row.get(mapping.color_indicator)).replace(",", " ").split()
        if any(color.upper() not in set("WUBRG") for color in indicator):
            result.errors.append(ValidationIssue(severity="error", row_number=index, message=f"{row_id}: color_indicator must use W, U, B, R, G."))
        is_vehicle = _has_type_word(_text(row.get(mapping.subtypes)) or type_line, "Vehicle")
        if is_vehicle and (not power or not toughness):
            result.errors.append(ValidationIssue(
                severity="error", row_number=index,
                message=f"Cards row {index}: Vehicle '{name}' requires both power and toughness.",
            ))
        elif not is_vehicle and "Creature" not in type_line and (power or toughness):
            result.warnings.append(ValidationIssue(severity="warning", row_number=index, message=f"Cards row {index}: power/toughness supplied for noncreature '{name}'."))

    for name, count in name_counter.items():
        if count > 1:
            result.warnings.append(ValidationIssue(severity="warning", message=f"Duplicate card name '{name}' appears {count} times."))
    result.rarity_counts = dict(rarity_counter)


def _format_issue(issue: ValidationIssue) -> str:
    return f"- {issue.message}"


def _text(value: object) -> str:
    return "" if value is None else str(value).strip()


def _has_type_word(value: str, word: str) -> bool:
    return bool(re.search(rf"\b{re.escape(word)}\b", value, flags=re.IGNORECASE))


def _is_falseish(value: object) -> bool:
    return str(value).strip().lower() in {"false", "no", "0", "skip", "disabled"}


def _derived_type_line(row: dict[str, object], mapping: object) -> str:
    legacy = _text(row.get(mapping.type_line))
    if legacy:
        return legacy
    left = " ".join([_text(row.get(mapping.super_types)), _text(row.get(mapping.card_types))]).strip()
    right = _text(row.get(mapping.subtypes))
    return f"{left} - {right}" if right else left
